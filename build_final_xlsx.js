function computeBaseScore(predmety) {
  // Если в предметах есть Английский — пользователь его выбирает (он сильнее общества)
  return predmety.includes("Английский") ? COMBO_ENG : COMBO_SOC;
}

function computeRisk(margin) {
  if (margin >= 10)  return "🛡️ Гарантия";
  if (margin >= 0)   return "✅ Реалистично";
  if (margin >= -20) return "⚡ На грани";
  return "🔥 Только платно / олимпиада";
}
